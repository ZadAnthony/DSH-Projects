import { readFile, mkdir, writeFile, realpath } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const promptRoot = resolve(projectRoot, 'workspace/packages/projects/prompts')
const generatedPath = resolve(projectRoot, 'workspace/packages/projects/src/prompts/catalog.generated.ts')
const prompts = [
  ['common.md', 'PROJECT_COMMON_PROMPT'],
  ['main.md', 'PROJECT_MAIN_PROMPT'],
  ['execution.md', 'PROJECT_EXECUTION_PROMPT'],
  ['memory-bot.md', 'PROJECT_MEMORY_BOT_PROMPT'],
  ['session-manager.md', 'MAIN_SESSION_MANAGER_PROMPT'],
  ['compaction.md', 'PROJECT_COMPACTION_INSTRUCTION'],
]

async function renderAgentPrompts() {
  const exports = await Promise.all(prompts.map(async ([file, name]) => {
    const body = (await readFile(resolve(promptRoot, file), 'utf8')).replace(/\r\n/g, '\n').trimEnd()
    if (body.length === 0) throw new Error(`Agent prompt is empty: ${file}`)
    return `export const ${name} = ${JSON.stringify(body)}\n`
  }))
  return '// Generated from workspace/packages/projects/prompts/*.md. Do not edit this file.\n'
    + '// Run: node scripts/sync-agent-prompts.mjs\n\n' + exports.join('\n')
}

/** 构建前只校验；正文或生成面不同步时由调用方终止构建。 */
export async function checkAgentPrompts() {
  const expected = await renderAgentPrompts()
  const actual = await readFile(generatedPath, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return undefined
    throw error
  })
  if (actual !== expected) throw new Error('Agent prompts are out of sync. Run: node scripts/sync-agent-prompts.mjs')
}

export async function writeAgentPrompts() {
  const generated = await renderAgentPrompts()
  await mkdir(dirname(generatedPath), { recursive: true })
  await writeFile(generatedPath, generated, 'utf8')
}

const entryPath = process.argv[1] === undefined ? undefined : await realpath(resolve(process.argv[1])).catch(() => undefined)
if (fileURLToPath(import.meta.url) === entryPath) {
  const args = process.argv.slice(2)
  if (args.length > 1 || args.some(arg => arg !== '--check')) {
    console.error('Usage: node scripts/sync-agent-prompts.mjs [--check]')
    process.exitCode = 1
  } else {
    try {
      await (args.includes('--check') ? checkAgentPrompts() : writeAgentPrompts())
      console.log(args.includes('--check') ? 'Agent prompts are synchronized.' : 'Agent prompt catalog generated.')
    } catch (error) {
      console.error(error instanceof Error ? error.message : String(error))
      process.exitCode = 1
    }
  }
}
